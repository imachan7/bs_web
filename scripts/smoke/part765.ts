// 追加シンボルは、その召喚の軽減に数える（公式Q&A Q3206：場にカメレオプスだけで、コスト7・軽減赤3を4コストで召喚できる）
import { scenario } from "./scenario"

const CHAMELE = "BS13-003" // カメレオプス
const VOLGAND = "BS17-008" // 紅玉の巨龍ボルガンド（赤・コスト7・軽減赤3）

// シンボル1+2=3で軽減赤3が満つ → コスト7から3引いて4を支払う
console.log("=== 1. カメレオプス：自分のメインステップでコスト7以上を召喚するとき赤シンボル2つ追加 ===")
scenario({
    name: "chameleon-in",
    start: { me: { spirits: [{ card: CHAMELE, label: "カメレ" }], hand: [VOLGAND] } },
    steps(t) {
        t.act("me", { type: "summon", handIndex: 0 })
    },
    expect: [
        "自分.リザーブ: 10 → 5",
        "自分.トラッシュのコア: 0 → 4",
        "自分.手札: 紅玉の巨龍ボルガンド → なし",
        "自分.紅玉の巨龍ボルガンド.場所: なし → フィールド",
        "自分.紅玉の巨龍ボルガンド.疲労: なし → false",
        "自分.紅玉の巨龍ボルガンド.コア: なし → 1",
        "自分.紅玉の巨龍ボルガンド.Lv: なし → 1",
        "自分.紅玉の巨龍ボルガンド.BP: なし → 4000",
    ],
})

console.log("=== 2. カメレオプス：相手のターンには軽減に数えない（相手が召喚しても自分のカメレオプスは関係ない） ===")
scenario({
    name: "chameleon-opp",
    start: { turn: "opp", me: { spirits: [{ card: CHAMELE, label: "カメレ" }] }, opp: { hand: [VOLGAND] } },
    steps(t) {
        t.act("opp", { type: "summon", handIndex: 0 })
    },
    expect: [
        "相手.リザーブ: 10 → 2",
        "相手.トラッシュのコア: 0 → 7",
        "相手.手札: 紅玉の巨龍ボルガンド → なし",
        "相手.紅玉の巨龍ボルガンド.場所: なし → フィールド",
        "相手.紅玉の巨龍ボルガンド.疲労: なし → false",
        "相手.紅玉の巨龍ボルガンド.コア: なし → 1",
        "相手.紅玉の巨龍ボルガンド.Lv: なし → 1",
        "相手.紅玉の巨龍ボルガンド.BP: なし → 4000",
    ],
})

console.log("すべてのチェックに合格しました 🎉（part765）")
